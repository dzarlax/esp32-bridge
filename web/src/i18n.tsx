const catalogs: Record<Exclude<UILocale, "ru">, Record<MessageKey, string>> = {
  en: enCatalog,
  "sr-Latn": srCatalog,
};
export function translationCatalogKeys(locale: Exclude<UILocale, "ru">): MessageKey[] {
  return Object.keys(catalogs[locale]) as MessageKey[];
}

const LocaleContext = createContext<{ locale: UILocale; setLocale: (value: UILocale) => void }>({ locale: "ru", setLocale: () => undefined });
export function normalizeLocale(value: unknown): UILocale {
  return value === "en" || value === "sr-Latn" || value === "ru" ? value : "ru";
}
export function readUILocale(): UILocale {
  try { return normalizeLocale(window.localStorage.getItem(storageKey)); } catch { return "ru"; }
}
export function writeUILocale(value: UILocale) {
  try { window.localStorage.setItem(storageKey, value); } catch { /* the in-memory locale still applies for this session */ }
}
export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<UILocale>(() => readUILocale());
  const setLocale = useCallback((value: UILocale) => { writeUILocale(value); setLocaleState(value); }, []);
  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = `HomeDash — ${translateText("Настройки", locale)}`;
  }, [locale]);
  return <LocaleContext.Provider value={{ locale, setLocale }}>{children}</LocaleContext.Provider>;
}
export function useLocale() {
  return useContext(LocaleContext);
}
export function useT() {
  const { locale } = useLocale();
  return useCallback((message: string) => translateText(message, locale), [locale]);
}
export function translateText(message: string, locale: UILocale): string {
  const normalized = message.replace(/\s+/g, " ").trim();
  if (locale === "ru") return normalized;
  const range = normalized.match(/^Введите целое число от (\d+) до (\d+) сек\.$/);
  if (range) {
    const [min, max] = range.slice(1);
    return locale === "en" ? `Enter a whole number from ${min} to ${max} sec.` : `Unesite ceo broj od ${min} do ${max} sek.`;
  }
  const validation = normalized.match(/^(Запуск после бездействия|Интервал смены фотографии): (Введите целое число от (\d+) до (\d+) сек\.)$/);
  if (validation) return `${translateText(validation[1]!, locale)}: ${translateText(validation[2]!, locale)}`;
  const unitLine = normalized.match(/^От (\d+) до (\d+) сек\.$/);
  if (unitLine) return locale === "en" ? `From ${unitLine[1]} to ${unitLine[2]} sec.` : `Od ${unitLine[1]} do ${unitLine[2]} sek.`;
  const urlHelp = normalized.match(/^(.+): общий адрес подключения для всех дисплеев\.$/);
  if (urlHelp) return `${translateText(urlHelp[1]!, locale)}${locale === "en" ? ": shared connection address for all displays." : ": zajednička adresa veze za sve ekrane."}`;
  const secretHelp = normalized.match(/^(.+)\. Сохранённое значение нельзя прочитать; новое значение заменит его\.$/);
  if (secretHelp) return `${translateText(secretHelp[1]!, locale)}${locale === "en" ? ". The saved value cannot be read; a new value will replace it." : ". Sačuvana vrednost se ne može pročitati; nova vrednost će je zameniti."}`;
  const versionConfirm = normalized.match(/^Устройство установит версию (.+) и может перезагрузиться\. Не отключайте питание\.$/);
  if (versionConfirm) return locale === "en" ? `The device will install version ${versionConfirm[1]} and may restart. Do not disconnect power.` : `Uređaj će instalirati verziju ${versionConfirm[1]} i možda će se ponovo pokrenuti. Ne isključujte napajanje.`;
  return catalogs[locale][normalized as MessageKey] ?? normalized;
}
export function dateLocale(locale: UILocale): string {
  return locale === "en" ? "en-GB" : locale === "sr-Latn" ? "sr-Latn-RS" : "ru-RU";
}

export function LanguageSelect({ className = "" }: { className?: string }) {
  const { locale, setLocale } = useLocale();
  const t = useT();
  return <label className={`language-select ${className}`}><span>{t("Язык интерфейса")}</span><select aria-label={t("Выберите язык интерфейса")} value={locale} onChange={(event) => setLocale(normalizeLocale(event.target.value))}><option value="ru">Русский</option><option value="en">English</option><option value="sr-Latn">Srpski (latinica)</option></select></label>;
}
