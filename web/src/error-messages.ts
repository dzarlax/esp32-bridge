export function errorMessage(code: string, fallback: string) {
  return Object.hasOwn(messages, code) ? messages[code] : fallback;
}

export function apiErrorMessage(code: string, status: number) {
  const fallback = status === 401
    ? "Сеанс завершён или вход не выполнен. Войдите снова."
    : status === 403
      ? "Действие не разрешено. Обновите страницу и повторите попытку."
      : status === 429
        ? "Слишком много попыток. Подождите немного и повторите действие."
        : status >= 500
          ? "Bridge временно не может выполнить запрос. Повторите попытку позже."
          : "Не удалось выполнить действие. Проверьте введённые данные и повторите попытку.";
  return errorMessage(code, fallback);
}
